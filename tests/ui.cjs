// Requires Playwright with Chromium. Run from the repository root.
const {chromium}=require('playwright'),path=require('node:path'),fs=require('node:fs/promises'),os=require('node:os'),assert=require('node:assert/strict');
(async()=>{
  const tmp=await fs.mkdtemp(path.join(os.tmpdir(),'zang-beta-'));
  const browser=await chromium.launch({executablePath:process.env.CHROMIUM_PATH||undefined,args:['--no-sandbox']});
  try{
    const page=await browser.newPage({viewport:{width:1440,height:950},acceptDownloads:true});
    const errors=[];page.on('pageerror',e=>errors.push(e.message));
    await page.goto(require('node:url').pathToFileURL(path.resolve('Zang-Pitch-Correction-AI.html')).href);
    const click=async id=>{await page.locator('#'+id).click();await page.waitForFunction(()=>!document.body.classList.contains('working'));};
    await click('demo');assert.equal(await page.locator('.track').count(),3);
    await click('tune');await page.getByText('BGV alignment',{exact:true}).click();await click('align');
    const h=await page.evaluate(()=>hits.find(h=>h.i===0&&h.ni===0));
    const canvas=page.locator('canvas');await canvas.scrollIntoViewIfNeeded();
    const rect=await canvas.boundingBox();
    const hitX=rect.x+h.x+h.w*.5,hitY=rect.y+h.y;
    await page.mouse.click(hitX,hitY,{button:'right'});
    await page.getByRole('button',{name:'Pitch',exact:true}).hover();
    const palette=page.locator('#toolPalette');
    assert.equal((await palette.innerText()).trim(),'');
    assert.equal(await palette.getByRole('button',{name:'Pitch',exact:true}).count(),1);
    const bounds=await Promise.all(['Pitch','Pitch modulation','Pitch drift'].map(label=>palette.getByRole('button',{name:label,exact:true}).boundingBox()));
    assert.ok(bounds[0].x===bounds[1].x && bounds[1].x===bounds[2].x && bounds[0].y<bounds[1].y && bounds[1].y<bounds[2].y);
    await palette.getByRole('button',{name:'Pitch modulation',exact:true}).click();
    assert.equal(await page.evaluate(()=>activeTool),'mod');
    await page.mouse.click(hitX,hitY,{button:'right'});
    await page.getByRole('button',{name:'Main tool',exact:true}).click();
    assert.equal(await page.locator('#inspector').count(),0);
    await page.keyboard.down('Shift');await page.keyboard.down('Alt');await page.keyboard.down('Meta');
    await page.mouse.click(hitX,hitY);
    await page.keyboard.up('Meta');await page.keyboard.up('Alt');await page.keyboard.up('Shift');
    assert.ok(await page.locator('#zoom').inputValue()>1);
    assert.equal(await page.evaluate(()=>monitorVoice),null);
    await page.keyboard.down('Alt');await page.keyboard.down('Meta');
    await page.mouse.move(rect.x+220,rect.y+100);await page.mouse.down();
    await page.mouse.move(rect.x+165,rect.y+150,{steps:4});await page.mouse.up();
    await page.keyboard.up('Meta');await page.keyboard.up('Alt');
    assert.ok(await page.evaluate(()=>+$('zoom').value>2 && pitchZoom>1));
    const originBefore=await page.evaluate(()=>timelineScale.origin);
    await canvas.dispatchEvent('wheel',{shiftKey:true,deltaY:80,deltaMode:0});
    assert.ok(await page.evaluate(()=>timelineScale.origin)>originBefore);
    await page.evaluate(()=>{pitchZoom=1;$('timeline').scrollTop=0;});
    await page.locator('#zoom').press('End');assert.ok(await page.locator('#zoom').inputValue()>48);
    await page.locator('#zoom').press('Home');
    const vol=page.getByRole('slider',{name:'Volume Lead vocal',exact:true});
    const pan=page.getByRole('slider',{name:'Pan Lead vocal',exact:true});
    await vol.press('ArrowDown');await pan.press('Shift+ArrowRight');
    assert.equal(await vol.getAttribute('aria-valuenow'),'-1');
    assert.equal(await pan.getAttribute('aria-valuenow'),'10');
    await canvas.scrollIntoViewIfNeeded();
    const fresh=await canvas.boundingBox();
    await page.mouse.move(fresh.x+h.x+h.w*.5,fresh.y+h.y);
    await page.mouse.down();
    await page.waitForFunction(()=>monitorVoice?.audio?.src.buffer.length>0);
    assert.ok(await page.evaluate(()=>monitorVoice.audio.src.buffer.getChannelData(0).some(x=>Math.abs(x)>.001)));
    const source=await page.evaluateHandle(()=>monitorVoice.audio.src);
    await page.mouse.move(fresh.x+h.x+h.w*.5,fresh.y+h.y-15,{steps:4});
    await page.waitForFunction(src=>monitorVoice.audio.src===src && Math.abs(src.detune.value)>1,source);
    await page.evaluate(()=>new Promise(resolve=>setTimeout(resolve,160)));
    assert.ok(await page.evaluate(src=>monitorVoice.audio.src===src && src.loopStart>0 && src.loopEnd>src.loopStart,source));
    await source.dispose();
    await page.mouse.up();assert.ok(await page.evaluate(()=>!!note() && monitorVoice===null));
    const pitch=await page.evaluate(()=>note().pitch);
    await click('undo');await click('redo');assert.equal(await page.evaluate(()=>tracks[0].notes[0].pitch),pitch);
    await page.mouse.click(fresh.x+150,fresh.y+10);
    const anchor=await page.evaluate(()=>position);assert.ok(anchor>0);
    await click('play');await page.waitForFunction(()=>liveTime()>position+.15);await click('play');
    assert.equal(await page.evaluate(()=>position),anchor);
    await page.selectOption('#view','overlay');await click('play');assert.equal(await page.locator('#play').textContent(),'■ Stop');
    await pan.press('ArrowRight');await page.waitForFunction(()=>playing && Math.abs(mixerNodes.get(tracks[0]).panner.pan.value-.11)<.002);
    await pan.press('ArrowLeft');await click('ab');await click('play');
    const file=async(id,name)=>{
      const wait=page.waitForEvent('download');await click(id);const d=await wait;const f=path.join(tmp,name);await d.saveAs(f);return f;
    };
    const session=await file('save','test.zpitch'), stems=await file('export','stems.zip');
    await page.locator('.projectMenu summary').click();
    const wav=await file('stem','lead.wav');
    assert.ok((await fs.stat(stems)).size>100000);assert.ok((await fs.readFile(wav)).subarray(0,4).toString()==='RIFF');
    await page.locator('#projectFile').setInputFiles(session);await page.waitForFunction(()=>document.getElementById('status').textContent.includes('restored'));
    assert.equal(await page.evaluate(()=>tracks[0].notes[0].pitch),pitch);
    assert.equal(await page.evaluate(()=>tracks[0].volume),-1);assert.equal(await page.evaluate(()=>tracks[0].pan),.1);
    await page.locator('#audioFiles').setInputFiles(wav);await page.waitForFunction(()=>document.querySelectorAll('.track').length===4);
    const accompaniment=await page.evaluate(()=>{
      const rate=12000,ch=Float32Array.from({length:rate},(_,i)=>
        [48,52,55].reduce((value,p)=>value+.16*Math.sin(2*Math.PI*midiHz(p)*i/rate),0));
      return Array.from(wavBytes([ch],rate));
    });
    await page.locator('#backingFile').setInputFiles({name:'Band.wav',mimeType:'audio/wav',buffer:Buffer.from(accompaniment)});
    await page.waitForFunction(()=>!busy && chordGuide()?.frames[3]?.root===0);
    assert.equal(await page.locator('#chordGuide option:checked').textContent(),'Band.wav');
    await click('tune');
    assert.equal(await page.evaluate(()=>tracks[0].notes[0].pitchLocked),true);
    assert.equal(await page.evaluate(()=>tracks[0].notes[0].pitch),pitch);
    assert.ok(await page.evaluate(()=>tracks[1].notes.some(n=>n.pitchReview?.root===0)));
    const savedGuide=await file('save','guided.zpitch');
    await page.locator('#projectFile').setInputFiles(savedGuide);
    await page.waitForFunction(()=>!busy && document.getElementById('status').textContent.includes('restored'));
    assert.equal(await page.locator('#chordGuide option:checked').textContent(),'Band.wav');
    assert.ok(await page.evaluate(()=>chordGuide().frames[3].tones.includes(4)));
    await page.getByText('Pitch settings',{exact:true}).click();await page.selectOption('#chordGuide','-1');
    await page.waitForFunction(()=>!busy && chordGuide()===null);
    assert.deepEqual(errors,[]);
    if(process.env.SCREENSHOT)await page.screenshot({path:process.env.SCREENSHOT});
    console.log('PASS: offline file launch, three-track demo, tuning, guide alignment, mouse editing, undo/redo, A/B playback, original-rate WAV and ZIP export, project recall and WAV import.');
  } finally{await browser.close();await fs.rm(tmp,{recursive:true,force:true});}
})().catch(e=>{console.error(e);process.exitCode=1;});
